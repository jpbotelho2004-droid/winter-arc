const BY_ID = new Map(LIBRARY.map((e) => [e.id, e]))

export function builtinExercise(id: string): ExerciseDef | undefined {
  return BY_ID.get(id)
}

export function isBuiltin(id: string): boolean {
  return BY_ID.has(id)
}

/** Distância/altura/tempo conforme o tipo de registo. */
export function exerciseMatches(e: ExerciseDef, q: string): boolean {
  const t = q.trim().toLowerCase()
  if (!t) return true
  const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
  const hay = norm(`${e.namePt} ${e.nameEn} ${MUSCLE_LABEL[e.primary]} ${e.equipment}`)
  return hay.includes(norm(t))
}
